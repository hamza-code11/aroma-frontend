"use client";

import { useEffect, useState } from "react";
import { X, Plus, ArrowRight, Loader2 } from "lucide-react"; // Loader2 import kiya
import type { Category } from "@/types/category";
import styles from "./CreateCategoryModal.module.css";

type Props = {
  open: boolean;
  onClose: () => void;
  onSubmit: (payload: Omit<Category, "id">) => void;
  isLoading?: boolean; // Loading state prop add ki
};

export default function CreateCategoryModal({
  open,
  onClose,
  onSubmit,
  isLoading = false, // Default false
}: Props) {
  const [name, setName] = useState("");
  const [isActive, setIsActive] = useState(true);
  const [status, setStatus] = useState<"idle" | "error">("idle");
  const [message, setMessage] = useState("");

  // Reset on open
  useEffect(() => {
    if (open) {
      setName("");
      setIsActive(true);
      setStatus("idle");
      setMessage("");
    }
  }, [open]);

  // Esc + body scroll lock
  useEffect(() => {
    if (!open) return;

    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape" && !isLoading) onClose();
    };
    document.addEventListener("keydown", onKey);

    const prev = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    return () => {
      document.removeEventListener("keydown", onKey);
      document.body.style.overflow = prev;
    };
  }, [open, onClose, isLoading]);

  if (!open) return null;

  const handleBackdrop = (e: React.MouseEvent<HTMLDivElement>) => {
    // Agar loading ho rahi hai toh backdrop par click kar ke close na ho
    if (e.target === e.currentTarget && !isLoading) onClose();
  };

  const handleNameChange = (value: string) => {
    setName(value);
    if (status !== "idle") {
      setStatus("idle");
      setMessage("");
    }
  };

  const handleSubmit = (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();

    // Sirf basic validation frontend par
    if (name.trim().length < 2) {
      setStatus("error");
      setMessage("Please enter a category name (min 2 characters).");
      return;
    }

    // Slug field hata diya hai, backend khud bana lega
    onSubmit({
      name: name.trim(),
      is_active: isActive,
    } as any); 
  };

  return (
    <div
      className={styles.backdrop}
      onMouseDown={handleBackdrop}
      role="presentation"
    >
      <div
        className={styles.dialog}
        role="dialog"
        aria-modal="true"
        aria-labelledby="create-cat-title"
      >
        <button
          type="button"
          className={styles.close}
          onClick={onClose}
          disabled={isLoading}
          aria-label="Close"
        >
          <X size={18} strokeWidth={1.5} />
        </button>

        <header className={styles.header}>
          <span className={styles.iconWrap} aria-hidden="true">
            <Plus size={20} strokeWidth={1.8} />
          </span>
          <div>
            <p className={styles.eyebrow}>New category</p>
            <h2 id="create-cat-title" className={styles.title}>
              Create Category
            </h2>
          </div>
        </header>

        <form className={styles.form} onSubmit={handleSubmit} noValidate>
          {/* Name */}
          <div className={styles.field}>
            <label htmlFor="create-cat-name" className={styles.label}>
              Name <span className={styles.required}>*</span>
            </label>
            <input
              id="create-cat-name"
              type="text"
              className={styles.input}
              placeholder="e.g. Aroma Diffusers"
              value={name}
              onChange={(e) => handleNameChange(e.target.value)}
              aria-invalid={status === "error" && name.trim().length < 2}
              autoFocus
              disabled={isLoading}
              required
            />
            <p className={styles.hint}>
              The slug will be automatically generated by the system.
            </p>
          </div>

          {/* Active */}
          <div className={styles.field}>
            <span className={styles.label}>Status</span>
            <label className={styles.checkbox}>
              <input
                type="checkbox"
                checked={isActive}
                onChange={(e) => {
                  setIsActive(e.target.checked);
                  if (status !== "idle") {
                    setStatus("idle");
                    setMessage("");
                  }
                }}
                disabled={isLoading}
              />
              <span className={styles.checkboxBox} aria-hidden="true" />
              <span className={styles.checkboxText}>
                Active (visible on storefront)
              </span>
            </label>
          </div>

          {/* Status */}
          <p
            className={`${styles.status} ${
              status === "error" ? styles.statusError : ""
            }`}
            role="status"
            aria-live="polite"
          >
            {message}
          </p>

          {/* Actions */}
          <div className={styles.actions}>
            <button
              type="button"
              className={styles.cancelBtn}
              onClick={onClose}
              disabled={isLoading}
            >
              Cancel
            </button>
            <button type="submit" className={styles.submitBtn} disabled={isLoading}>
              {isLoading ? (
                <>
                  Creating...
                  <Loader2 size={15} strokeWidth={2} className="animate-spin" />
                </>
              ) : (
                <>
                  Create Category
                  <ArrowRight size={15} strokeWidth={1.8} />
                </>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
